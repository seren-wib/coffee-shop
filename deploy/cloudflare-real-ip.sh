#!/usr/bin/env bash
# Write /etc/nginx/cloudflare-real-ip.conf from Cloudflare's published ranges (SDD 10.3, 11.1).
# Run again when Cloudflare changes its ranges, then `nginx -t && systemctl reload nginx`.
set -euo pipefail

out=/etc/nginx/cloudflare-real-ip.conf
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

{
  echo "# Generated by deploy/cloudflare-real-ip.sh on $(date -u +%F). Do not edit."
  for list in ips-v4 ips-v6; do
    curl -fsS "https://www.cloudflare.com/$list" | while read -r range; do
      [ -n "$range" ] && echo "set_real_ip_from $range;"
    done
  done
} >"$tmp"

count=$(grep -c '^set_real_ip_from' "$tmp")
if [ "$count" -lt 10 ]; then
  echo "cloudflare-real-ip: only $count ranges fetched, keeping the old file" >&2
  exit 1
fi
install -m 644 "$tmp" "$out"
echo "cloudflare-real-ip: $count ranges written to $out"
